#!/usr/bin/env python3
"""Import the user-supplied Hold Infinity archive; preserve source and transpile GPU math to GLSL 4.10."""
import hashlib
import itertools
import json
import math
from pathlib import Path
import re
import sys
import zipfile

ROOT=Path(__file__).resolve().parents[1]/'demos/infinity'


def dot(a,b): return sum(x*y for x,y in zip(a,b))
def cross(a,b): return [a[1]*b[2]-a[2]*b[1], a[2]*b[0]-a[0]*b[2], a[0]*b[1]-a[1]*b[0]]
def geometry():
    faces=[]; phi=(1+math.sqrt(5))/2
    for a,b in itertools.product((-1,1),repeat=2):
        for v in ([0,a,b*phi],[a,b*phi,0],[b*phi,0,a]):
            n=math.sqrt(dot(v,v)); faces.append([x/n for x in v])
    vertices=[]; owners=[]
    for a,b,c in itertools.combinations(range(12),3):
        if all(abs(dot(faces[i],faces[j])-1/math.sqrt(5))<1e-6 for i,j in ((a,b),(b,c),(a,c))):
            bc=cross(faces[b],faces[c]); ca=cross(faces[c],faces[a]); ab=cross(faces[a],faces[b]); det=dot(faces[a],bc)
            vertices.append([(bc[i]+ca[i]+ab[i])/det for i in range(3)]); owners.append({a,b,c})
    edges=[(vertices[i],vertices[j]) for i,j in itertools.combinations(range(20),2) if len(owners[i]&owners[j])==2]
    assert len(vertices)==20 and len(edges)==30
    return faces,vertices,edges


def main():
    archive=Path(sys.argv[1]); raw=archive.read_bytes()
    names={'style.css','gl.js','grin.js','index.html','instrument.js','app.js','dodeca.js','chamber.js'}
    with zipfile.ZipFile(archive) as z:
        if set(z.namelist())!=names or any(i.file_size>1000000 for i in z.infolist()):
            raise SystemExit('Unexpected archive members or sizes')
        src={n:z.read(n).decode('utf-8') for n in sorted(names)}
    ref=ROOT/'reference'; ref.mkdir(parents=True,exist_ok=True)
    for n,s in src.items(): (ref/n).write_text(s)
    faces,vertices,edges=geometry(); t=5**-.25
    rf=t/(1+math.sqrt(1-t*t)); sc=(rf+1/rf)/2; sr=(1/rf-rf)/2
    vr=math.sqrt(dot(vertices[0],vertices[0])); kv=t*vr; rv=kv/(1+math.sqrt(1-kv*kv))
    replacements={'PHYS.nCentre.toFixed(4)':'1.3000','RHO_V.toFixed(6)':f'{rv:.6f}', 'D_FLAT.toFixed(6)':f'{rv/vr:.6f}',
                  'SPH_C.toFixed(6)':f'{sc:.6f}','SPH_R.toFixed(6)':f'{sr:.6f}',
                  'LAYER_D.toFixed(6)':f'{math.log(1/(1-rv*rv))/7:.6f}', '(PHYS.layers - 1).toFixed(1)':'6.0',
                  'KLEIN_T.toFixed(7)':f'{t:.7f}', 'EPS.toFixed(4)':'0.0450','DISPERSION.toFixed(4)':'0.0700',
                  'CHUNK':'32','STEPS':'512','STEPS - 1':'511'}
    common=re.search(r'const COMMON = `([\s\S]*?)`;',src['grin.js']).group(1)
    def convert(s):
        s=s.replace('${COMMON}', common)
        for k,v in replacements.items():s=s.replace('${'+k+'}',v)
        s=s.replace('#version 300 es','#version 410 core')
        s=re.sub(r'^precision [^;]+;\s*','',s,flags=re.M)
        if '${' in s:raise ValueError('Unresolved template interpolation')
        return s
    shaders={}
    for file,variables in [('gl.js',['FULLSCREEN_VS']),('instrument.js',['TRACE_FS','SHOW_FS']),('grin.js',['INTEGRATE_FS','FIELD_FS','RAY_VS','RAY_FS'])]:
        for var in variables:
            val=re.search(r'(?:export )?const '+var+r' = `([\s\S]*?)`;',src[file]).group(1)
            shaders[var]=convert(val)
    chamber=re.search(r'const FS = \(mode\) => `([\s\S]*?)`;',src['chamber.js']).group(1)
    expr="${mode === 'cube' ? 'FLAT' : mode.toUpperCase()}"
    for mode in ['object','cube','flat','hyper']:
        shaders['CHAMBER_'+mode.upper()]=convert(chamber.replace(expr,'FLAT' if mode=='cube' else mode.upper()))
    shaders['CHAMBER_POST']=convert(re.search(r'const POST_FS = `([\s\S]*?)`;',src['chamber.js']).group(1))
    header='// Generated by tools/import_hold_infinity.py; source attribution in SOURCE.md.\n#pragma once\nnamespace infinity_shader {\n'
    for name,s in shaders.items():header+='inline constexpr const char* '+name+'=R"HOLD('+s+')HOLD";\n'
    header+='}\n';(ROOT/'Shaders.hpp').write_text(header)
    def array(name,data,width):
        return 'inline constexpr float '+name+'[] = {'+','.join(f'{v:.9f}f' for row in data for v in row)+'};\n'
    geom='#pragma once\nnamespace infinity_geometry {\ninline constexpr float kleinT='+f'{t:.9f}f;\n'
    geom+=array('faces',faces,3)+array('vertices',vertices,3)+array('edgeA',[e[0] for e in edges],3)+array('edgeB',[e[1] for e in edges],3)+'}\n'
    (ROOT/'Dodecahedron.hpp').write_text(geom)
    (ROOT/'source.json').write_text(json.dumps({'archive':archive.name,'sha256':hashlib.sha256(raw).hexdigest(),'files':{n:hashlib.sha256(s.encode()).hexdigest() for n,s in src.items()},'shaders':sorted(shaders)},indent=2)+'\n')
    print('Imported 12 shader programs/stages and dodecahedral geometry')


if __name__=='__main__': main()
